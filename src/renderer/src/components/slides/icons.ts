export const ICON_NAMES = Object.keys(ICONS)

/** Full inline SVG for `name`, or null when the name is unknown. */
export function iconSvg(name: string, size = 20): string | null {
  const inner = ICONS[name]
  if (!inner) return null
  return S(inner, size)
}

/**
 * Expand `{{icon:name}}` placeholders into inline SVG spans.
 * Unknown names are left untouched so a typo stays visible (and editable).
 */
export function expandIcons(md: string): string {
  return md.replace(/\{\{icon:([a-z0-9-]+)\}\}/g, (m, name: string) => {
    const svg = iconSvg(name)
    return svg ? `<span class="slide-icon">${svg}</span>` : m
  })
}
